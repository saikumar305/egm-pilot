"""Build the GitHub Pages site.

Reads each skill's SKILL.md frontmatter, so the site cannot drift from the skills, and writes
site/data/skills.js (the skill cards) and site/autopilot/flow.html (copied from docs/).
Both outputs are generated and git-ignored.

  python3 site/tools/build.py           build the site
  python3 site/tools/build.py --check   validate only (used in pull requests)

Standard library only.
"""

import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SITE = ROOT / "site"
SKILLS_DIR = ROOT / "skills"
# Display fields every entry in site/src/skills.json must have.
FIELDS = ("group", "icon", "title", "command", "purpose", "use_when", "you_get", "example")


def read_frontmatter(path: Path) -> dict:
    lines = path.read_text(encoding="utf-8").splitlines()
    if not lines or lines[0].strip() != "---":
        raise ValueError(f"{path}: no frontmatter")
    end = lines.index("---", 1)
    fields = {}
    i = 1
    while i < end:
        match = re.match(r"^([A-Za-z_][\w-]*):\s*(.*)$", lines[i])
        if not match:
            i += 1
            continue
        key, value = match.group(1), match.group(2).strip()
        if value in (">", ">-", "|", "|-"):
            block = []
            i += 1
            while i < end and (lines[i].startswith(" ") or lines[i] == ""):
                if lines[i].strip():
                    block.append(lines[i].strip())
                i += 1
            fields[key] = " ".join(block)
            continue
        fields[key] = value.strip("\"'")
        i += 1
    return fields


def validate(entries: list) -> list:
    errors = []
    names = [e["name"] for e in entries]
    if len(names) != len(set(names)):
        errors.append("site/src/skills.json: duplicate skill names")

    on_disk = {}
    for skill_md in sorted(SKILLS_DIR.glob("*/SKILL.md")):
        fm = read_frontmatter(skill_md)
        on_disk[fm.get("name", "")] = skill_md

    for entry in entries:
        name = entry["name"]
        if name not in on_disk:
            errors.append(f"{name}: no skills/*/SKILL.md declares this name")
            continue
        for field in FIELDS:
            if not entry.get(field):
                errors.append(f"{name}: missing '{field}' in site/src/skills.json")
        if not entry.get("command", "").startswith("/egm-pilot:"):
            errors.append(f"{name}: command must start with /egm-pilot: (the plugin prefix)")

    for name in sorted(set(on_disk) - set(names)):
        errors.append(f"{name}: has a SKILL.md but no entry in site/src/skills.json")
    return errors


def build_skill_records(entries: list) -> list:
    records = []
    for entry in entries:
        skill_md = next(
            p for p in SKILLS_DIR.glob("*/SKILL.md")
            if read_frontmatter(p).get("name") == entry["name"]
        )
        fm = read_frontmatter(skill_md)
        records.append({
            "name": entry["name"],
            **{field: entry[field] for field in FIELDS},
            "description": fm.get("description", ""),
            "source": str(skill_md.relative_to(ROOT)),
        })
    return records


def write_outputs(entries: list) -> None:
    site_config = json.loads((SITE / "src" / "site.json").read_text(encoding="utf-8"))
    records = build_skill_records(entries)

    payload = json.dumps({"site": site_config, "skills": records}, ensure_ascii=False, indent=2)
    # Keep "</script>" from ending the script tag early.
    payload = payload.replace("</", "<\\/")
    data_dir = SITE / "data"
    data_dir.mkdir(parents=True, exist_ok=True)
    (data_dir / "skills.js").write_text(
        "// Generated by site/tools/build.py. Do not edit.\n"
        f"window.EGM = {payload};\n",
        encoding="utf-8",
    )

    walkthrough = ROOT / "docs" / "autopilot-flow.html"
    if walkthrough.exists():
        (SITE / "autopilot").mkdir(parents=True, exist_ok=True)
        shutil.copyfile(walkthrough, SITE / "autopilot" / "flow.html")


def main(argv: list) -> int:
    entries = json.loads((SITE / "src" / "skills.json").read_text(encoding="utf-8"))
    errors = validate(entries)
    if errors:
        print("site build failed:", file=sys.stderr)
        for error in errors:
            print(f"  - {error}", file=sys.stderr)
        return 1
    if "--check" in argv:
        print(f"ok: {len(entries)} skills match their SKILL.md files")
        return 0
    write_outputs(entries)
    print(f"built site: {len(entries)} skills -> {SITE / 'data' / 'skills.js'}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
